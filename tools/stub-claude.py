#!/usr/bin/env python3
"""A stand-in for the `claude` binary, so the add-on can be tested without an account.

It answers the handful of invocations the add-on makes and, for a run, produces
real `stream-json` output plus a session transcript in the layout Claude Code uses.
That is what makes the chat, the history, streaming and cancellation testable.

Behaviour is steered by environment variables:

    STUB_SLEEP         seconds to spend "thinking", so a run can be cancelled
    STUB_CHILD         fork a grandchild that keeps working, the way a subagent does
    STUB_FAIL          exit non-zero with an is_error result
    STUB_NOTICE        report a warning and a failed tool call during the turn
    STUB_TOOLS         report a couple of tool calls, as a long run would
    STUB_API_ERROR     answer with a synthetic API error instead of a reply
    STUB_VERSION       what --version reports before anything is installed
    STUB_INSTALL_TO    what installing a channel leaves behind (default 9.9.99)
    STUB_INSTALL_FAIL  make `claude install` fail
"""

import json
import os
import re
import sys
import time
import uuid
from pathlib import Path

HOME = Path(os.environ.get("HOME", "/tmp"))
PROJECTS = HOME / ".claude" / "projects"
# What `install` wrote, so the stand-in reports a new version afterwards the way a
# real install does. Without this an update could never be seen to change anything.
INSTALLED_MARKER = HOME / ".stub-installed-version"


def emit(record: dict) -> None:
    sys.stdout.write(json.dumps(record) + "\n")
    sys.stdout.flush()


def transcript_path(session: str) -> Path:
    slug = re.sub(r"[^A-Za-z0-9]", "-", os.getcwd())
    directory = PROJECTS / slug
    directory.mkdir(parents=True, exist_ok=True)
    return directory / f"{session}.jsonl"


def append(session: str, record: dict) -> None:
    with transcript_path(session).open("a") as handle:
        handle.write(json.dumps({**record, "sessionId": session}) + "\n")


def run(argv: list) -> int:
    prompt = sys.stdin.read().strip()

    resume = None
    if "--resume" in argv:
        resume = argv[argv.index("--resume") + 1]
    session = resume or str(uuid.uuid4())

    # /rename is what writes a user-set title; /compact is a no-op that succeeds.
    rename = re.match(r"/rename\s+(.+)", prompt)
    if rename:
        title = rename.group(1)
        # The real CLI puts three records in the transcript for one /rename, all of
        # them ordinary `user` messages: the caveat, the command, and its output.
        # They are machinery, and reproducing them here is what proves they stay out
        # of the chat window.
        for content in (
            "<local-command-caveat>Caveat: The messages below were generated by the "
            "user while running local commands. DO NOT respond to these messages or "
            "otherwise consider them in your response unless the user explicitly asks "
            "you to.</local-command-caveat>",
            f"<command-name>/rename</command-name>\n<command-message>rename"
            f"</command-message>\n<command-args>{title}</command-args>",
            "<local-command-stdout></local-command-stdout>",
        ):
            append(session, {"type": "user", "message": {"role": "user", "content": content},
                             "timestamp": "2026-01-01T00:00:02.000Z"})
        append(session, {"type": "custom-title", "customTitle": title})
        # The CLI answers a local command with a message it wrote itself, marked
        # `<synthetic>`. It is bookkeeping, not a reply, and it was being shown as
        # one — so the stand-in writes it too.
        append(session, {"type": "assistant", "isApiErrorMessage": False,
                         "message": {"role": "assistant", "model": "<synthetic>",
                                     "content": [{"type": "text",
                                                  "text": "No response requested."}]},
                         "timestamp": "2026-01-01T00:00:03.000Z"})
        emit({"type": "result", "subtype": "success", "is_error": False, "result": "",
              "session_id": session, "num_turns": 0})
        return 0
    if prompt.startswith("/compact"):
        emit({"type": "result", "subtype": "success", "is_error": False, "result": "",
              "session_id": session, "num_turns": 0})
        return 0

    emit({"type": "system", "subtype": "init", "session_id": session,
          "permissionMode": "manual", "capabilities": []})
    append(session, {"type": "user", "message": {"role": "user", "content": prompt},
                     "timestamp": "2026-01-01T00:00:00.000Z"})

    if os.environ.get("STUB_API_ERROR"):
        # An API error is a message the CLI wrote itself, and the one synthetic
        # message that is worth showing — beside the conversation, not in it.
        append(session, {"type": "assistant", "isApiErrorMessage": True,
                         "message": {"role": "assistant", "model": "<synthetic>",
                                     "content": [{"type": "text", "text":
                                                  "API Error: model temporarily "
                                                  "unavailable"}]},
                         "timestamp": "2026-01-01T00:00:00.600Z"})

    if os.environ.get("STUB_NOTICE"):
        # Both shapes the real CLI uses to report trouble that is not the turn
        # failing: its own levelled `system` record, and a tool result marked as an
        # error. A tool error is not a text block, so it never reads as a message.
        append(session, {"type": "system", "subtype": "informational", "level": "warning",
                         "content": "Unknown command: /rname. Did you mean /rename?",
                         "timestamp": "2026-01-01T00:00:00.500Z"})
        append(session, {"type": "user", "message": {"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": "toolu_stub", "is_error": True,
             "content": "<tool_use_error>File has not been read yet."
                        "</tool_use_error>"}]},
            "timestamp": "2026-01-01T00:00:00.700Z"})

    if os.environ.get("STUB_FAIL"):
        emit({"type": "result", "subtype": "error", "is_error": True,
              "result": "stub failure", "session_id": session})
        return 1

    if os.environ.get("STUB_TOOLS"):
        # Tool calls, the way the real CLI reports them: this is what a caller polling
        # a long run is shown while no words are being produced.
        for name, arguments in (
            ("Read", {"file_path": "/data/jobs/x/in/notes.docx"}),
            ("Bash", {"command": "python3 -c 'zipfile'"}),
        ):
            emit({"type": "assistant", "message": {"role": "assistant", "content": [
                {"type": "tool_use", "id": f"toolu_{name}", "name": name, "input": arguments}]}})

    # Every request the CLI makes reports the prompt it sent, and the prompt grows as
    # the turn goes on. A subagent's own request is in there too, and it is somebody
    # else's conversation. The totals in the result event add all of these up, which is
    # exactly why the size of the window in use cannot be read from them.
    for size, extra in ((400, {}), (900, {"parent_tool_use_id": "toolu_Task"}), (600, {})):
        emit({"type": "assistant", **extra, "message": {
            "role": "assistant", "content": [{"type": "text", "text": "thinking"}],
            "usage": {"input_tokens": 10, "cache_read_input_tokens": size - 10}}})

    # A subagent, or a Bash tool call: work that happens in a child of this process, which
    # is why the add-on signals the whole process group rather than the CLI alone. The child
    # writes a byte a tenth of a second into the job's own directory, so a test can see
    # whether it stopped when the turn was frozen.
    if os.environ.get("STUB_CHILD") and os.fork() == 0:
        ticks = Path.cwd() / "child-ticks"
        parent = os.getppid()
        try:
            # And it goes when the turn goes: an orphan left ticking would outlive the test
            # that made it, as one did.
            while os.getppid() == parent:
                with ticks.open("ab") as handle:
                    handle.write(b".")
                time.sleep(0.1)
        finally:
            os._exit(0)

    # Words arrive one at a time, which is what the partial reply is read from.
    reply = f"stub reply to: {prompt[:60]}"
    sleep = float(os.environ.get("STUB_SLEEP", "0"))

    # Written before the streaming finishes, as the real CLI does: its transcript
    # grows during the turn, not only at the end.
    append(session, {"type": "assistant",
                     "message": {"role": "assistant", "content": [{"type": "text", "text": reply}]},
                     "timestamp": "2026-01-01T00:00:01.000Z"})

    for index, word in enumerate(reply.split()):
        piece = ("" if index == 0 else " ") + word
        emit({"type": "stream_event",
              "event": {"delta": {"type": "text_delta", "text": piece}}})
        if sleep:
            time.sleep(sleep / max(len(reply.split()), 1))

    append(session, {"type": "ai-title", "aiTitle": f"About {prompt[:30]}"})

    emit({"type": "result", "subtype": "success", "is_error": False, "result": reply,
          "session_id": session, "num_turns": 1,
          "usage": {"input_tokens": 10, "cache_creation_input_tokens": 100,
                    "cache_read_input_tokens": 1000},
          "modelUsage": {"stub-model": {"contextWindow": 10000, "inputTokens": 10,
                                        "cacheReadInputTokens": 1000}}})
    return 0


def mcp_config_paths(scope: str) -> tuple:
    """Where the real CLI keeps each scope: (file, path inside it)."""
    if scope == "project":
        return Path.cwd() / ".mcp.json", ("mcpServers",)
    if scope == "local":
        return HOME / ".claude.json", ("projects", str(Path.cwd()), "mcpServers")
    return HOME / ".claude.json", ("mcpServers",)


def mcp(argv: list) -> int:
    """`add-json` and `remove`, writing the files the real CLI writes."""
    scope = "local"
    if "-s" in argv:
        scope = argv[argv.index("-s") + 1]
    elif "--scope" in argv:
        scope = argv[argv.index("--scope") + 1]
    if scope not in {"user", "local", "project"}:
        print(f"stub: unknown scope {scope}", file=sys.stderr)
        return 1

    path, keys = mcp_config_paths(scope)
    try:
        config = json.loads(path.read_text())
    except (OSError, ValueError):
        config = {}

    section = config
    for key in keys[:-1]:
        section = section.setdefault(key, {})
    servers = section.setdefault(keys[-1], {})

    if argv[:1] == ["add-json"]:
        name, definition = argv[1], argv[2]
        servers[name] = json.loads(definition)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(config, indent=2))
        print(f"Added stdio MCP server {name} to {scope} config")
        return 0

    if argv[:1] == ["remove"]:
        name = argv[1]
        if name not in servers:
            print(f"stub: no MCP server {name} in {scope}", file=sys.stderr)
            return 1
        del servers[name]
        path.write_text(json.dumps(config, indent=2))
        print(f"Removed MCP server {name} from {scope} config")
        return 0

    print("stub: unhandled mcp invocation", argv, file=sys.stderr)
    return 2


def main() -> int:
    argv = sys.argv[1:]

    if "--version" in argv:
        version = os.environ.get("STUB_VERSION", "9.9.9")
        if INSTALLED_MARKER.is_file():
            version = INSTALLED_MARKER.read_text().strip()
        print(f"{version} (Claude Code)" if version else "")
        return 0

    if argv[:1] == ["install"]:
        if os.environ.get("STUB_INSTALL_FAIL"):
            print("install refused by the stub", file=sys.stderr)
            return 1
        target = argv[1] if len(argv) > 1 else "latest"
        # A channel installs whatever it currently points at; a version installs
        # itself, which is what makes "reinstalling the same one" testable.
        version = target if re.fullmatch(r"[0-9]+(\.[0-9]+)*", target) else os.environ.get(
            "STUB_INSTALL_TO", "9.9.99"
        )
        INSTALLED_MARKER.parent.mkdir(parents=True, exist_ok=True)
        INSTALLED_MARKER.write_text(version)
        print(f"installed {version}")
        return 0

    if argv[:1] == ["mcp"]:
        return mcp(argv[1:])

    if argv[:1] == ["plugin"]:
        if argv[1:3] == ["marketplace", "update"]:
            print("marketplaces updated")
            return 0
        if argv[1:3] == ["list", "--json"]:
            print(json.dumps([{"name": "demo-plugin"}]))
            return 0
        if argv[1:2] == ["update"]:
            print("plugin updated")
            return 0
        return 0

    if "-p" in argv:
        return run(argv)

    print("stub: unhandled invocation", argv, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
